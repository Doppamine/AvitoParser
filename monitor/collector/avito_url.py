"""Адрес объявления с датами и числом гостей.

Проверено вживую 29.08: страница объявления принимает `checkIn`/`checkOut`
и число гостей прямо в адресе, после чего цена на этот период считается
на клиенте отдельным запросом. Это лучший из трёх рассматривавшихся исходов:
сбор превращается в цикл по периодам без единого клика по календарю.

Число гостей задаётся всегда и одинаковое для всех объявлений в одном сборе.
Цена от него зависит, поэтому снимок на двоих и снимок на четверых сравнивать
нельзя — та же ошибка, что сравнение периодов разной длины.
"""

import json
from urllib.parse import quote

from django.conf import settings

from monitor.validators import normalize_avito_url

GUESTS_PARAM = 'guestsDetailed'
# Версия схемы самой площадки, а не наша. Стоит числом рядом с полями, которые
# она описывает: если площадка её сменит, ломаться должно здесь и заметно.
GUESTS_SCHEMA_VERSION = 1


def guests_payload(guests: int) -> str:
    """Значение `guestsDetailed`: JSON, который площадка кладёт в адрес.

    Собирается из числа гостей, а не хранится готовой строкой: строка молча
    разъедется с настройкой, и сбор пойдёт на двоих, когда просили четверых.

    Все гости — взрослые. Дети — ещё одна ось сопоставимости (у площадки
    свои правила по возрастам), и заводить её, пока заказчик о ней не сказал,
    значит городить то, чем никто не пользуется.
    """
    return json.dumps(
        {
            'version': GUESTS_SCHEMA_VERSION,
            'totalCount': guests,
            'adultsCount': guests,
            'children': [],
        },
        separators=(',', ':'),
    )


def with_dates(url: str, interval=None, guests: int | None = None) -> str:
    """Адрес, по которому идёт сбор: объявление плюс период и число гостей.

    Исходная ссылка сначала приводится к каноническому виду — схема, домен,
    путь, — и только потом получает наши параметры. Правило одно на весь проект:
    ссылка из адресной строки может тащить чужие `checkIn` и гостей, а ссылка
    из выдачи — метку сессии поиска `context`. Дописывать своё к чужому значит
    отправлять запрос, который никто не читал целиком.
    """
    guests = settings.COLLECT_GUESTS if guests is None else guests

    ours = [f'{GUESTS_PARAM}={quote(guests_payload(guests), safe="")}']
    if interval is not None:
        ours[:0] = [
            f'checkIn={interval.check_in.isoformat()}',
            f'checkOut={interval.check_out.isoformat()}',
        ]

    return f'{normalize_avito_url(url)}?{"&".join(ours)}'
